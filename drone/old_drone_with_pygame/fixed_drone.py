def main() -> None:
    args = parse_args()

    print("Connect this computer to the drone Wi-Fi first.")
    print("[INFO] RTSP URL:", args.url)
    altitude_hold = not args.no_altitude_hold
    speed = normalize_speed_byte(args.speed)
    print("[INFO] Packet speed:", speed)
    print("[INFO] Axis delta:", args.axis_delta)
    print("[INFO] Hover throttle:", clamp_byte(args.hover_throttle))
    print("[INFO] Trim AIL/ELE/RUDD:", args.trim_ail, args.trim_ele, args.trim_rudd)
    print("[INFO] Altitude hold:", altitude_hold)
    print("[INFO] Video:", "off" if args.no_video else "on")
    if not args.no_video:
        print("[INFO] Capture dir:", args.capture_dir)
    if args.video_debug:
        print("[INFO] Video debug: on")
    if args.video_dump_dir:
        print("[INFO] Video dump dir:", args.video_dump_dir)

    session = RtspUdpSession(
        host=args.host,
        port=args.port,
        url=args.url,
        client_port_base=args.client_port,
        verbose=args.verbose_rtsp,
    )
    viewer: RtpVideoViewer | None = None
    if not args.no_video:
        viewer = RtpVideoViewer(
            session,
            debug=args.video_debug,
            debug_limit=args.video_debug_limit,
            dump_dir=args.video_dump_dir,
            dump_limit=args.video_dump_limit,
            capture_dir=args.capture_dir,
        )
        session.add_rtp_callback(viewer.on_rtp_packet)

    controller = DroneController(
        session,
        speed=speed,
        axis_delta=args.axis_delta,
        altitude_hold=altitude_hold,
        hover_throttle=args.hover_throttle,
        trim_ail=args.trim_ail,
        trim_ele=args.trim_ele,
        trim_rudd=args.trim_rudd,
    )

    try:
        session.connect()
        if viewer is not None:
            viewer.start()

        # Send neutral a few times so the command path is warm before key input.
        neutral = build_htjr_packet(controller.neutral())
        for _ in range(5):
            session.send_control(neutral)
            time.sleep(args.send_interval)

        if args.terminal:
            run_terminal(controller, args.send_interval, viewer)
        else:
            run_pygame(controller, args.send_interval, viewer)
    finally:
        print("[INFO] closing")
        controller.print_hover_adjust_summary()
        try:
            neutral = build_htjr_packet(controller.neutral())
            for _ in range(5):
                session.send_control(neutral)
                time.sleep(args.send_interval)
        except Exception:
            pass
        if viewer is not None:
            viewer.stop()
        session.close()


if __name__ == "__main__":
    main()
